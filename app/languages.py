DEFAULT = "ja"
_HANGUL = re.compile(r"[가-힣]")


def get(code: str | None) -> dict:
    return LANGS.get(code or DEFAULT, LANGS[DEFAULT])


def is_korean(text: str) -> bool:
    return bool(_HANGUL.search(text or ""))


def est_seconds(text: str) -> float:
    """Ước tính thời lượng đọc theo chữ hiển thị (tự nhận ra tiếng Hàn)."""
    text = text or ""
    if is_korean(text):
        return len(text.replace(" ", "")) / LANGS["ko"]["cps"]
    return len(text) / LANGS["ja"]["cps"]
